/**
 * Regenerates the icon sprite from lucide-react. Run after adding an icon to
 * src/components/icons.tsx: `node scripts/build-icons.mjs`.
 *
 * Icons render as <use> references to this one file because inline SVG was a
 * quarter of the static HTML on the busiest pages (see check-text-ratio.mjs).
 *
 * The file is public/icons/<hash>.svg, named by its content, and src/lib/icon-sprite.ts
 * holds that name. A changed sprite therefore gets a new URL: under a fixed name, browsers
 * and Cloudflare's edge kept serving the old copy for a day, and a new icon showed blank.
 * /icons/* is immutable in public/_headers. Commit both files.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const ICONS = [
  "arrow-left", "arrow-right", "arrow-up-right", "check", "chevron-left", "chevron-right",
  "external-link", "facebook", "headphones", "image", "instagram", "mail", "map-pin",
  "message-circle", "pause", "phone", "play", "shield", "shopping-cart", "truck", "video", "wrench", "x",
];

const WHATSAPP =
  "M17.472 14.382c-.297-.149-1.758-.867-2.03-.967-.273-.099-.471-.148-.67.15-.197.297-.767.966-.94 1.164-.173.199-.347.223-.644.075-.297-.15-1.255-.463-2.39-1.475-.883-.788-1.48-1.761-1.653-2.059-.173-.297-.018-.458.13-.606.134-.133.298-.347.446-.52.149-.174.198-.298.298-.497.099-.198.05-.371-.025-.52-.075-.149-.669-1.612-.916-2.207-.242-.579-.487-.5-.669-.51-.173-.008-.371-.01-.57-.01-.198 0-.52.074-.792.372-.272.297-1.04 1.016-1.04 2.479 0 1.462 1.065 2.875 1.213 3.074.149.198 2.096 3.2 5.077 4.487.709.306 1.262.489 1.694.625.712.227 1.36.195 1.871.118.571-.085 1.758-.719 2.006-1.413.248-.694.248-1.289.173-1.413-.074-.124-.272-.198-.57-.347m-5.421 7.403h-.004a9.87 9.87 0 01-5.031-1.378l-.361-.214-3.741.982.998-3.648-.235-.374a9.86 9.86 0 01-1.51-5.26c.001-5.45 4.436-9.884 9.888-9.884 2.64 0 5.122 1.03 6.988 2.898a9.825 9.825 0 012.893 6.994c-.003 5.45-4.437 9.884-9.885 9.884m8.413-18.297A11.815 11.815 0 0012.05 0C5.495 0 .16 5.335.157 11.892c0 2.096.547 4.142 1.588 5.945L.057 24l6.305-1.654a11.882 11.882 0 005.683 1.448h.005c6.554 0 11.89-5.335 11.893-11.893a11.821 11.821 0 00-3.48-8.413z";

const require = createRequire(import.meta.url);
const iconDir = path.join(path.dirname(require.resolve("lucide-react")), "..", "esm", "icons");

function symbol(name) {
  const source = fs.readFileSync(path.join(iconDir, `${name}.js`), "utf8");
  const nodes = [...source.matchAll(/\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]/g)].map(([, tag, attrs]) => {
    const parts = [...attrs.matchAll(/(\w+): "([^"]*)"/g)]
      .filter(([, key]) => key !== "key")
      .map(([, key, value]) => `${key}="${value}"`);
    return `<${tag} ${parts.join(" ")}/>`;
  });
  if (nodes.length === 0) throw new Error(`No shapes found for icon: ${name}`);
  return `<symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${nodes.join("")}</symbol>`;
}

const svg = [
  '<svg xmlns="http://www.w3.org/2000/svg">',
  `<symbol id="whatsapp" viewBox="0 0 24 24"><path d="${WHATSAPP}"/></symbol>`,
  ...ICONS.map(symbol),
  "</svg>",
  "",
].join("\n");

const hash = crypto.createHash("sha256").update(svg).digest("hex").slice(0, 8);
const url = `/icons/${hash}.svg`;
fs.rmSync("public/icons", { recursive: true, force: true });
fs.mkdirSync("public/icons");
fs.writeFileSync(`public${url}`, svg);
fs.writeFileSync(
  "src/lib/icon-sprite.ts",
  `// Generated by scripts/build-icons.mjs. The name is the sprite's content hash, so a changed\n` +
    `// sprite gets a new URL and no browser or edge cache serves an old copy.\n` +
    `export const ICON_SPRITE = "${url}";\n`,
);
console.log(`${url}: ${ICONS.length + 1} icons, ${svg.length} bytes`);
